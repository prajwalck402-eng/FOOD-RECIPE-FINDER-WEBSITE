class RecipeTranslator {
  constructor() {
    this.cache = new Map();
  }

  getDictionaryTerm(key, lang = 'en') {
    if (lang === 'en') return key;
    return CULINARY_DICTIONARY[lang]?.[key] || key;
  }

  // Get matching pre-translation or match title keywords
  getPretranslation(recipe, lang) {
    if (!recipe || !recipe.title || lang === 'en') return null;
    const t = (recipe.title || '').toLowerCase();

    for (const [key, transObj] of Object.entries(REGIONAL_PRETRANSLATED_RECIPES)) {
      if (t.includes(key) && transObj[lang]) {
        return transObj[lang];
      }
    }
    return null;
  }

  // Translate full recipe into target language with cache & API fallback
  async translateRecipe(recipe, targetLang = 'hi') {
    if (!recipe || targetLang === 'en') {
      return recipe;
    }

    const cacheKey = `${recipe._id || recipe.title}_${targetLang}`;
    if (this.cache.has(cacheKey)) {
      return this.cache.get(cacheKey);
    }

    // 1. Check local instant pretranslations for instant 0ms response
    const pretrans = this.getPretranslation(recipe, targetLang);
    if (pretrans) {
      const merged = {
        ...recipe,
        title: pretrans.title || recipe.title,
        description: pretrans.description || recipe.description,
        instructions: (recipe.instructions || []).map((orig, idx) => {
          const transStep = pretrans.instructions?.[idx];
          return {
            stepNumber: idx + 1,
            instruction: transStep?.instruction || (typeof orig === 'string' ? orig : orig.instruction || ''),
            durationMinutes: orig.durationMinutes || 5,
            chefTip: transStep?.chefTip || orig.chefTip || ''
          };
        })
      };
      this.cache.set(cacheKey, merged);
      return merged;
    }

    // 2. Fetch live Groq AI translation for custom/new recipes
    try {
      const res = await fetch('/api/ai/translate-recipe', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ recipe, targetLanguage: targetLang })
      });
      const data = await res.json();
      if (data.success && data.translatedRecipe) {
        this.cache.set(cacheKey, data.translatedRecipe);
        return data.translatedRecipe;
      }
    } catch (e) {
      console.warn('Recipe live translation error:', e);
    }

    return recipe;
  }
}

export const recipeTranslator = new RecipeTranslator();
export default recipeTranslator;
